    private void initializeScreen() {
        try {
            if (currentUser == null) {
                currentUser = userService.findByUsername("admin");
            }
            if (currentUser == null) {
                showMessage("The admin account was not found.");
                return;
            }
            makeTablesReadOnly();
            loadDashboard();
            loadInventory();
        } catch (SQLException exception) {
            showDatabaseError();
        }
    }

    // Dashboard panel: loads system summaries and recent rentals.
    private void loadDashboard() {
        try {
            jLabel32.setText(String.valueOf(itemService.countAll(currentUser.getId())));
            jLabel33.setText(String.valueOf(rentalService.countByStatus("Pending", currentUser.getId())));
            jLabel34.setText(String.valueOf(rentalService.countByStatus("Rented", currentUser.getId())));
            jLabel35.setText(String.valueOf(rentalService.countReturnedToday(currentUser.getId())));
            DefaultTableModel model = createModel(new String[]{"ID", "Customer", "Item", "Qty", "Price", "Stock", "Rental Date", "Return Date", "Status"});
            for (Rental rental : rentalService.getRecentRentals(currentUser.getId())) {
                model.addRow(new Object[]{
                    rental.getId(),
                    rental.getCustomerName(),
                    rental.getItemName(),
                    rental.getQuantity(),
                    formatPrice(rental.getPrice()),
                    rental.getStock(),
                    rental.getRentalDate(),
                    rental.getReturnDate(),
                    rental.getStatus()
                });
            }
            jTable1.setModel(model);
        } catch (SQLException exception) {
            showDatabaseError();
        }
    }

    // Inventory panel: loads the Admin's clothing items.
    private void loadInventory() {
        try {
            String category = String.valueOf(jComboBox1.getSelectedItem());
            String size = String.valueOf(jComboBox2.getSelectedItem());
            String status = String.valueOf(jComboBox3.getSelectedItem());
            List<ClothingItem> items = itemService.getItems(cleanSearch
        (jTextField1.getText(), "Search by ID, Name, or Color"), 
                    category, size, "", status, currentUser.getId());
            DefaultTableModel model = createModel(new String[]
            {"ID", "Item Name", "Price", "Stock", "Category", "Size", "Color", "Status", "Action"});
            for (ClothingItem item : items) {
                model.addRow(new Object[]{item.getId(), 
                    item.getItemName(), 
                    formatPrice(item.getPrice()), 
                    item.getStock(), 
                    item.getCategory(), 
                    item.getSize(), 
                    item.getColor(), 
                    item.getAvailabilityStatus(), 
                    "Edit️ / Delete"});
            }
            INVENTORYCELL.setModel(model);
            jLabel16.setText(String.valueOf(items.size()));
        } catch (SQLException exception) {
            showDatabaseError();
        }
    }

