    // Inventory row: edits, deletes, or views an item.
    private void inventoryAction() {
        int row = INVENTORYCELL.getSelectedRow();
        if (row < 0) {
            return;
        }
        try {
            int itemId = Integer.parseInt(INVENTORYCELL.getValueAt(row, 0).toString());
            ClothingItem item = itemService.findById(itemId, currentUser.getId());
            Object[] options = {"Edit", "Delete", "View", "Cancel"};
            int choice = JOptionPane.showOptionDialog(this, "Choose an action for this item.", "Inventory", JOptionPane.DEFAULT_OPTION, JOptionPane.PLAIN_MESSAGE, null, options, options[0]);
            if (choice == 0) {
                ClothingItem updatedItem = ItemDialog.showDialog(this, item);
                if (updatedItem != null) {
                    itemService.save(updatedItem, currentUser.getId());
                    loadInventory();
                }
            } else if (choice == 1) {
                int confirmation = JOptionPane.showConfirmDialog(this, "Delete this item?", "Confirm Delete", JOptionPane.YES_NO_OPTION);
                if (confirmation == JOptionPane.YES_OPTION) {
                    itemService.delete(itemId, currentUser.getId());
                    loadInventory();
                }
            } else if (choice == 2 && item != null) {
                showMessage(item.getItemName() + "\nPrice per Day: " + formatPrice(item.getPrice()) + "\nCategory: " + item.getCategory() + "\nSize: " + item.getSize() + "\nColor: " + item.getColor() + "\nStatus: " + item.getStatus() + "\nDescription: " + item.getDescription());
            }
        } catch (SQLException | IllegalArgumentException exception) {
            showMessage(exception.getMessage());
        }
    }

    // Rental Request row: approves or rejects a request.
    private void rentalRequestAction() {
        int row = jTable3.getSelectedRow();
        if (row < 0) {
            return;
        }
        int rentalId = Integer.parseInt(jTable3.getValueAt(row, 0).toString());
        String status = String.valueOf(jTable3.getValueAt(row, 8));
        if (!"Pending".equalsIgnoreCase(status)) {
            showMessage("Only pending requests can be approved or rejected.");
            return;
        }
        Object[] options = {"Approve", "Reject", "Cancel"};
        int choice = JOptionPane.showOptionDialog
        (this, "Choose an action for this rental request.", 
                "Rental Request", JOptionPane.DEFAULT_OPTION, JOptionPane.PLAIN_MESSAGE, null, options, options[0]);
        try {
            if (choice == 0) {
                rentalService.approve(rentalId, currentUser.getId());
                showMessage("Rental request approved.");
            } else if (choice == 1) {
                rentalService.reject(rentalId, currentUser.getId());
                showMessage("Rental request rejected.");
            } else {
                return;
            }
            loadRentalRequests();
            loadDashboard();
            loadInventory();
        } catch (SQLException | IllegalArgumentException exception) {
            showMessage(exception.getMessage());
        }
    }

    // Return action: marks a rented item as returned.
    private void returnAction() {
        int row = jTable4.getSelectedRow();
        if (row < 0) {
            return;
        }
        int rentalId = Integer.parseInt(jTable4.getValueAt(row, 0).toString());
        int choice = JOptionPane.showConfirmDialog(this, "Mark this rental as returned?", "Return Item", JOptionPane.YES_NO_OPTION);
        if (choice != JOptionPane.YES_OPTION) {
            return;
        }
        try {
            rentalService.markReturned(rentalId, currentUser.getId());
            showMessage("Item marked as returned.");
            loadReturns();
            loadDashboard();
            loadInventory();
        } catch (SQLException | IllegalArgumentException exception) {
            showMessage(exception.getMessage());
        }
    }

    // Customer row: displays customer account details.
    private void viewCustomer() {
        int row = jTable5.getSelectedRow();
        if (row < 0) {
            return;
        }
        try {
            int customerId = Integer.parseInt(jTable5.getValueAt(row, 0).toString());
            User customer = userService.findById(customerId);
            if (customer != null) {
                String accountStatus = customer.isBlocked() ? "Blocked - return overdue items first" : "Active";
                showMessage("First Name: " + customer.getFirstName() + "\nLast Name: " + customer.getLastName() + "\nContact: " + customer.getContactNumber() + "\nEmail: " + customer.getEmail() + "\nUsername: " + customer.getUsername() + "\nAccount: " + accountStatus);
            }
        } catch (SQLException exception) {
            showDatabaseError();
        }
    }

    // My Profile label: opens the Admin profile dialog.
    private void showAdminProfile() {
        if (currentUser == null) {
            return;
        }
        try {
            boolean defaultPassword = userService.isDefaultAdminPassword(currentUser.getId());
            User updatedUser = AdminProfileDialog.showDialog(this, currentUser, defaultPassword);
            if (updatedUser == null) {
                return;
            }
            updatedUser.setId(currentUser.getId());
            updatedUser.setUsername(currentUser.getUsername());
            userService.updateAdminProfile(updatedUser);
            currentUser = userService.findById(currentUser.getId());
            showMessage("Admin profile updated successfully.");
        } catch (SQLException | IllegalArgumentException exception) {
            showMessage(exception.getMessage());
        }
    }

