    // Login screen checks the Laragon database connection.
    private boolean checkDatabase() {
        try (java.sql.Connection connection = DatabaseConnection.getConnection()) {
            return connection.isValid(2);
        } catch (SQLException exception) {
            JOptionPane.showMessageDialog(this, "Cannot connect to CRMS. Start MySQL in Laragon and try again.", "Database Error", JOptionPane.ERROR_MESSAGE);
            return false;
        }
    }

    // Login button authenticates the account.
    private void login() {
        if (!checkDatabase()) {
            return;
        }
        try {
            String username = Validation.required(txtFullname.getText(), "Username or full name");
            String password = new String(txtPassword.getPassword());
            Validation.password(password);
            User user = userService.authenticate(username, password);
            if (user == null) {
                throw new IllegalArgumentException("The login details are incorrect.");
            }
            openDashboard(user);
        } catch (SQLException | IllegalArgumentException exception) {
            JOptionPane.showMessageDialog(this, exception.getMessage(), "Login", JOptionPane.WARNING_MESSAGE);
        }
    }

    // Sign Up button creates a Customer account.
    private void register() {
        if (!checkDatabase()) {
            return;
        }
        try {
            String firstName = Validation.namePart(txtSignupFullname.getText(), "First name");
            String lastName = Validation.namePart(txtLastname.getText(), "Last name");
            String emailText = txtEmail.getText().trim();
            if (emailText.equalsIgnoreCase("Enter your Email")) {
                emailText = "";
            }
            String email = Validation.email(Validation.required(emailText, "Email"));
            String password = new String(txtPassword2.getPassword());
            String question = Validation.securityQuestion(String.valueOf(jComboBox1.getSelectedItem()));
            String answer = Validation.securityAnswer(txtSecurityAnswer.getText());
            Validation.password(password);
            String fullName = firstName + " " + lastName;
            User user = new User(0, fullName, firstName, lastName, "", email, password, "Customer", question, answer);
            userService.register(user);
            JOptionPane.showMessageDialog(this, "Account created. You can now log in.", "Sign Up", JOptionPane.INFORMATION_MESSAGE);
            clearSignUpFields();
            showLogin();
        } catch (SQLException | IllegalArgumentException exception) {
            JOptionPane.showMessageDialog(this, exception.getMessage(), "Sign Up", JOptionPane.WARNING_MESSAGE);
        }
    }

    // Forgot Password button resets the account password.
    private void resetPassword() {
        if (!checkDatabase()) {
            return;
        }
        try {
            String username = Validation.required(txtFullname2.getText(), "Username or full name");
            String question = Validation.securityQuestion(String.valueOf(jComboBox2.getSelectedItem()));
            String answer = Validation.securityAnswer(txtSecurityAnswer2.getText());
            String newPassword = new String(txtNewpass.getPassword());
            userService.resetPassword(username, question, answer, newPassword);
            JOptionPane.showMessageDialog(this, "Password reset successfully.", "Reset Password", JOptionPane.INFORMATION_MESSAGE);
            clearResetFields();
            showLogin();
        } catch (SQLException | IllegalArgumentException exception) {
            JOptionPane.showMessageDialog(this, exception.getMessage(), "Reset Password", JOptionPane.WARNING_MESSAGE);
        }
    }

    // Login process opens the correct dashboard.
    private void openDashboard(User user) {
        if ("Admin".equalsIgnoreCase(user.getRole())) {
            CRSGuiADMIN dashboard = new CRSGuiADMIN(user);
            dashboard.setLocationRelativeTo(null);
            dashboard.setVisible(true);
        } else {
            CRSGuiCUSTOMER dashboard = new CRSGuiCUSTOMER(user);
            dashboard.setLocationRelativeTo(null);
            dashboard.setVisible(true);
        }
        dispose();
    }

